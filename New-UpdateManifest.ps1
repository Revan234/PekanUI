param(
    [switch]$Check
)

$ErrorActionPreference = "Stop"
$root = [IO.Path]::GetFullPath($PSScriptRoot).TrimEnd('\')
$manifestPath = Join-Path $root "update-manifest.txt"
$paths = [System.Collections.Generic.List[string]]::new()

function Add-ManifestPath([string]$relativePath) {
    if (-not (Test-Path -LiteralPath (Join-Path $root ($relativePath -replace '/', '\')) -PathType Leaf)) {
        throw "File wajib manifest tidak ditemukan: $relativePath"
    }
    if (-not $paths.Contains($relativePath)) {
        $paths.Add($relativePath)
    }
}

Add-ManifestPath "uijtrp.lua"
Add-ManifestPath "uijtrp/web/sao_web.exe"

$browserFiles = @(
    "uijtrp/web/installed_from.txt",
    "uijtrp/web/LICENSES_filters.txt",
    "uijtrp/web/LICENSE_WebView2_SDK.txt",
    "uijtrp/web/NOTICE_WebView2_SDK.txt",
    "uijtrp/web/README.txt",
    "uijtrp/web/sao_web.json",
    "uijtrp/web/filters/easylist.txt",
    "uijtrp/web/filters/easyprivacy.txt",
    "uijtrp/web/filters/urlhaus-filter-online.txt"
)

foreach ($browserFile in $browserFiles) {
    if (Test-Path -LiteralPath (Join-Path $root ($browserFile -replace '/', '\')) -PathType Leaf) {
        Add-ManifestPath $browserFile
    }
}

$allowedAssetExtensions = @(".bmp", ".gif", ".jpeg", ".jpg", ".m4a", ".mp3", ".ogg", ".png", ".webp", ".wav")
$uiRoot = Join-Path $root "uijtrp"
$uiFiles = @(Get-ChildItem -LiteralPath $uiRoot -File)
foreach ($directory in Get-ChildItem -LiteralPath $uiRoot -Directory | Where-Object { $_.Name -ne "web" }) {
    $uiFiles += Get-ChildItem -LiteralPath $directory.FullName -File -Recurse
}

foreach ($file in $uiFiles) {
    $relativePath = $file.FullName.Substring($root.Length + 1).Replace('\', '/')
    if ($relativePath -match '(^|/)\.') {
        continue
    }

    if ($relativePath -match '^uijtrp/web/') {
        continue
    }

    if ($relativePath -notmatch '^[A-Za-z0-9_.-]+(/[A-Za-z0-9_.-]+)*$') {
        continue
    }

    if ($file.Extension -ieq ".lua") {
        Add-ManifestPath $relativePath
        continue
    }

    if ($allowedAssetExtensions -notcontains $file.Extension.ToLowerInvariant()) {
        continue
    }

    $segments = $relativePath -split '/'
    $excluded = $false
    foreach ($segment in $segments) {
        if (($segment -match 'notif|notify|ringtone') -or
            (($segment -match 'logo') -and ($segment -match 'frame'))) {
            $excluded = $true
            break
        }
    }
    if (-not $excluded) {
        Add-ManifestPath $relativePath
    }
}

$orderedPaths = $paths.ToArray()
[Array]::Sort($orderedPaths, [StringComparer]::Ordinal)
$lines = @("# Generated by New-UpdateManifest.ps1; do not edit by hand.") + $orderedPaths
$contents = [string]::Join("`r`n", $lines) + "`r`n"

if ($Check) {
    $current = if (Test-Path -LiteralPath $manifestPath) {
        [IO.File]::ReadAllText($manifestPath).TrimStart([char]0xFEFF).Replace("`r`n", "`n").TrimEnd("`n")
    } else {
        ""
    }
    $expected = $contents.Replace("`r`n", "`n").TrimEnd("`n")
    if ($current -cne $expected) {
        Write-Error "update-manifest.txt tidak sinkron. Jalankan .\New-UpdateManifest.ps1 lalu commit hasilnya."
        exit 1
    }
    Write-Output "update-manifest.txt sudah sinkron ($($orderedPaths.Count) file)."
    exit 0
}

$encoding = [Text.UTF8Encoding]::new($false)
[IO.File]::WriteAllText($manifestPath, $contents, $encoding)
Write-Output "update-manifest.txt diperbarui ($($orderedPaths.Count) file)."
